import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { getAddress } from 'viem';
import { TransactionHashVariant } from 'genlayer-js/types';
import { createReadOnlyStudioClient } from '../lib/rpc-client';
const name = process.argv[2];
const files: Record<string, string> = { Watches:'watches.py', Claims:'claims.py', Challenges:'challenges.py', Bounties:'bounties.py', ChangeLedger:'change_ledger.py' };
if (!Object.hasOwn(files,name)) throw new Error('Choose a known application contract.');
const proof = JSON.parse(await readFile(new URL('../deploy/proof.json',import.meta.url),'utf8'));
const entry = proof.contracts[name];
const receipt = proof.receipts['deploy-'+name];
if (!entry || receipt?.stage !== 'FINALIZED_SUCCESS') throw new Error('Finalized recorded deployment required.');
let last=0,requests=0;
async function slot(){const wait=Math.max(0,last+2500-Date.now());if(wait)await new Promise(r=>setTimeout(r,wait));last=Date.now();requests++;}
const client=createReadOnlyStudioClient({beforeRequest:slot});
const code=await client.getContractCode(getAddress(entry.address));
const source=await readFile(new URL('../contracts/'+files[name],import.meta.url),'utf8');
const sourceMatches=createHash('sha256').update(code).digest('hex')===entry.sourceSha256 && createHash('sha256').update(source).digest('hex')===entry.sourceSha256;
const raw=await client.readContract({address:getAddress(entry.address),functionName:'get_config',args:[],transactionHashVariant:TransactionHashVariant.LATEST_FINAL});
const config=typeof raw==='string'?JSON.parse(raw):raw;
const ownerMatches=config.owner.toLowerCase()===receipt.account.toLowerCase();
const link='https://explorer-studio.genlayer.com/address/'+entry.address;
await slot();
const response=await fetch('https://explorer-studio.genlayer.com/api/address/'+entry.address,{headers:{'User-Agent':'Mozilla/5.0 FinePrint/1.0'},signal:AbortSignal.timeout(25000)});
const explorer=response.ok ? await response.json().catch(()=>null) : null;
const explorerMatches=response.ok && explorer?.type==='CONTRACT' && explorer?.address?.toLowerCase()===entry.address.toLowerCase();
await slot();
const page=await fetch(link,{headers:{'User-Agent':'Mozilla/5.0 FinePrint/1.0'},signal:AbortSignal.timeout(25000)});
const pageOpens=page.ok && page.url.toLowerCase()===link.toLowerCase();
console.log(JSON.stringify({ok:sourceMatches&&ownerMatches&&explorerMatches&&pageOpens,name,address:entry.address,explorer:link,sourceMatches,ownerMatches,explorerMatches,pageOpens,configured:config.configured,owner:config.owner,explorerStatus:response.status,pageStatus:page.status,requests}));
if(!sourceMatches||!ownerMatches||!explorerMatches||!pageOpens)process.exitCode=1;
